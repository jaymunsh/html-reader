#!/usr/bin/env python3
"""Split scripts/font-src/PretendardVariable.woff2 into unicode-range subsets (variable wght axis kept).

Usage (fonttools + brotli needed, e.g. in a throwaway venv):
  python3 -m venv /tmp/fontvenv && /tmp/fontvenv/bin/pip install fonttools brotli
  /tmp/fontvenv/bin/python scripts/subset-fonts.py

Writes public/__app/fonts/pretendard-<name>.woff2 and src/ui/theme/pretendard.css (the @font-face rules, with
unicode-range computed from each subset's real codepoints). Browsers fetch only the subsets a page's text needs;
the service worker precaches all of them (offline). Re-run only when the source font changes.
"""
import os
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'scripts/font-src/PretendardVariable.woff2')
OUT = os.path.join(ROOT, 'public/__app/fonts')
CSS = os.path.join(ROOT, 'src/ui/theme/pretendard.css')

cmap = TTFont(SRC).getBestCmap()
HANGUL = [c for c in sorted(cmap) if 0xAC00 <= c <= 0xD7A3]


def latin(c):  # Latin, punctuation, symbols, CJK punctuation, fullwidth forms
    return c < 0x2FF or 0x2000 <= c <= 0x2BFF or 0x3000 <= c <= 0x303F or 0xFF00 <= c <= 0xFFEF


def ks_x_1001():  # the 2350 everyday syllables
    s = set()
    for hi in range(0xB0, 0xC9):
        for lo in range(0xA1, 0xFF):
            try:
                s.add(ord(bytes([hi, lo]).decode('euc_kr')))
            except UnicodeDecodeError:
                pass
    return s & set(HANGUL)


common = ks_x_1001()
rest = [c for c in HANGUL if c not in common]
third = (len(rest) + 2) // 3
groups = {
    'latin': [c for c in cmap if latin(c)],
    'hangul-common': sorted(common),
    'hangul-2': rest[:third],
    'hangul-3': rest[third:2 * third],
    'hangul-4': rest[2 * third:],
}
used = {c for g in groups.values() for c in g}
groups['extra'] = [c for c in cmap if c not in used]  # jamo, kana, remaining symbols
assert sum(len(g) for g in groups.values()) == len(cmap)


def ranges(cps):
    cps = sorted(cps)
    out = []
    a = b = cps[0]
    for c in cps[1:]:
        if c == b + 1:
            b = c
            continue
        out.append((a, b))
        a = b = c
    out.append((a, b))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


css = ['/* Generated by scripts/subset-fonts.py: do not edit. */']
for name, cps in groups.items():
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.notdef_outline = True
    opts.name_IDs = ['*']
    f = subset.load_font(SRC, opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=cps)
    s.subset(f)
    assert 'fvar' in f and 'gvar' in f, 'variation axes lost'
    path = os.path.join(OUT, f'pretendard-{name}.woff2')
    subset.save_font(f, path, opts)
    print(f'{name:14} {len(cps):6} cp {os.path.getsize(path):9} bytes')
    css.append(f"@font-face {{ font-family: 'Pretendard Variable'; src: url('/__app/fonts/pretendard-{name}.woff2') format('woff2-variations'); "
               f"font-weight: 45 920; font-display: swap; unicode-range: {ranges(cps)}; }}")
with open(CSS, 'w') as fh:
    fh.write('\n'.join(css) + '\n')
